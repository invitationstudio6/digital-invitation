/* ----- TRANSLATION FUNCTION ----- */
function lunaT(key) {
    var lang = LUNA_LANG;
    if (LUNA_I18N[lang] && LUNA_I18N[lang][key]) {
        return LUNA_I18N[lang][key];
    }
    if (LUNA_I18N.en && LUNA_I18N.en[key]) {
        return LUNA_I18N.en[key];
    }
    return key;
}

function lunaSetLanguage(lang) {
    if (!LUNA_I18N[lang]) return;
    LUNA_LANG = lang;
    localStorage.setItem("lunaLanguage", lang);
    document.documentElement.lang = lang;

    document.querySelectorAll("[data-lang]").forEach(function(btn) {
        btn.classList.toggle("active", btn.getAttribute("data-lang") === lang);
    });

    document.querySelectorAll("[data-i18n]").forEach(function(el) {
        var key = el.getAttribute("data-i18n");
        var text = lunaT(key);
        if (text) el.innerHTML = text;
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach(function(el) {
        var key = el.getAttribute("data-i18n-placeholder");
        var text = lunaT(key);
        if (text) el.placeholder = text;
    });
}

function lunaInitLanguage() {
    document.querySelectorAll("[data-lang]").forEach(function(btn) {
        btn.addEventListener("click", function() {
            lunaSetLanguage(this.getAttribute("data-lang"));
        });
    });
    lunaSetLanguage(LUNA_LANG);
}

